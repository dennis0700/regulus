import AppKit
import Foundation
import Observation
import RegulusCore
import SwiftUI

/// 主窗口的状态：照片库内容、侧边栏与照片选择、最近一次导入、批量分析。
/// 存储属性都在这里，各功能的方法在同目录的 `LibraryModel+*.swift` 扩展里；为了让这些扩展能改状态，属性没有标
/// `private(set)`，视图只读它们，修改一律通过方法
/// Main window state: library contents, sidebar and photo selection, the last import, and batch analysis.
/// Stored properties live here and each feature's methods in the `LibraryModel+*.swift` extensions next to it; so
/// those extensions can change the state, the properties are not `private(set)`: views only read them and change
/// them through the methods.
@MainActor @Observable
final class LibraryModel {
    enum SidebarItem: Hashable {
        case all
        case recentImport
        case folder(URL)
        /// 某个星级的全部照片 / All photos with this many stars.
        case stars(Int)
        case flag(PhotoFlag)
    }

    /// 批量分析的进度 / Batch analysis progress.
    struct AnalysisProgress: Equatable {
        var tasks: AnalysisTasks = .all
        var done = 0
        var total = 0
        var failed = 0
        var loadingModels = false
    }

    // MARK: 照片库 / Library

    var snapshot: LibrarySnapshot?
    var isLoading = false
    var loadError: String?
    /// 最近一次导入的照片（含已存在而跳过的），只保存在内存里 / Photos from the last import (incl. skipped), in memory only.
    var recentImport: [LibraryPhoto] = []
    var sidebarSelection: SidebarItem? = .all {
        didSet {
            if oldValue != sidebarSelection {
                selection = []
                previewURL = nil
            }
        }
    }
    /// 正在预览的照片，nil 表示显示网格 / The photo being previewed; nil shows the grid.
    var previewURL: URL?
    var isImportPresented = false
    let thumbnails = ThumbnailCache()
    /// 每次 load 加一（含同一照片库的重新扫描），后台任务据此丢弃过期结果
    /// Bumped on every load (including rescans of the same library) so background tasks can drop stale results.
    var generation = 0
    /// 当前照片库根目录，最近一次 load 传入的 / The library root from the last load.
    var root: URL?
    /// 监听照片库和手动添加的文件夹，在 Finder 里改动后自动重新扫描
    /// Watches the library and added folders so changes made in Finder trigger a rescan.
    @ObservationIgnored var watcher: FolderWatcher?
    @ObservationIgnored var watchedPaths: [String] = []
    /// 分析进行中发生了外部改动，分析结束后再重新扫描 / An outside change happened during an analysis; rescan when it ends.
    @ObservationIgnored var rescanAfterAnalysis = false

    private static let addedFoldersKey = "addedFolders"
    /// 手动添加到侧边栏的文件夹（可以在照片库之外），按路径存在 UserDefaults
    /// Folders added to the sidebar by hand (may be outside the library), stored as paths in UserDefaults.
    var addedFolders: [URL] = (UserDefaults.standard.stringArray(forKey: LibraryModel.addedFoldersKey) ?? [])
        .map { URL(fileURLWithPath: $0) } {
        didSet { UserDefaults.standard.set(addedFolders.map(\.path), forKey: Self.addedFoldersKey) }
    }
    private static let excludedFoldersKey = "excludedFolders"
    /// 从侧边栏移除的照片库子文件夹，扫描时跳过 / Library subfolders removed from the sidebar; skipped when scanning.
    var excludedFolders: [URL] = (UserDefaults.standard.stringArray(forKey: LibraryModel.excludedFoldersKey) ?? [])
        .map { URL(fileURLWithPath: $0) } {
        didSet { UserDefaults.standard.set(excludedFolders.map(\.path), forKey: Self.excludedFoldersKey) }
    }
    private static let folderOrderKey = "folderOrder"
    /// 侧边栏文件夹的拖拽顺序（路径），同级之间按出现先后排；不在其中的排在后面
    /// Drag order of sidebar folders (paths); siblings sort by position here, unlisted ones go last.
    var folderOrder: [String] = UserDefaults.standard.stringArray(forKey: LibraryModel.folderOrderKey) ?? [] {
        didSet { UserDefaults.standard.set(folderOrder, forKey: Self.folderOrderKey) }
    }
    private static let pinnedFoldersKey = "pinnedFolders"
    /// 固定了位置的顶层文件夹（路径）/ Top-level folders whose position is fixed (paths).
    var pinnedFolders: Set<String> = Set(UserDefaults.standard.stringArray(forKey: LibraryModel.pinnedFoldersKey) ?? []) {
        didSet { UserDefaults.standard.set(Array(pinnedFolders), forKey: Self.pinnedFoldersKey) }
    }

    // MARK: 选择 / Selection

    var selection: Set<URL> = []
    /// ⇧ 点击时区间的起点 / Anchor for ⇧-click ranges.
    var selectionAnchor: URL?
    /// 框选开始时的选择和合并方式 / Selection and combine mode at the start of a marquee.
    var marqueeBase: Set<URL> = []
    var marqueeMode = MarqueeMode.replace

    // MARK: 分析 / Analysis

    /// ~/Library/Application Support/Regulus，模型在其下的 models/ / ~/Library/Application Support/Regulus; the models
    /// are in its models/ subfolder.
    let modelsRepo: URL = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        .appendingPathComponent("Regulus")
    @ObservationIgnored lazy var analyzer = PhotoAnalyzer(repo: modelsRepo)
    /// 名录信息（scripts/build_species_info.py 生成）；不在时不写也不显示鸟种
    /// Checklist info (generated by scripts/build_species_info.py); without it species are neither written nor shown.
    @ObservationIgnored lazy var speciesTable: SpeciesInfoTable? = try? SpeciesInfoTable(
        url: modelsRepo.appendingPathComponent("models/birdtrace/species_info.json"))
    /// 各地区的鸟种名录（在「设置 › 模型」里随模型下载，没装时不能按地区筛选）
    /// Species lists per region (downloaded with the models in Settings › Models; without it there is no region
    /// filter).
    var regionsURL: URL { modelsRepo.appendingPathComponent("models/regions.json") }
    /// 设置 › 模型 的下载状态；装好后重新读取名录 / Settings › Models download state; reloads the checklist once installed.
    @ObservationIgnored private(set) lazy var modelDownload = ModelDownloadModel(
        directory: modelsRepo.appendingPathComponent("models")) { [weak self] in
        guard let self else { return }
        speciesTable = try? SpeciesInfoTable(url: modelsRepo.appendingPathComponent("models/birdtrace/species_info.json"))
    }
    // 下面三项都从照片文件读出，键为照片 URL / The three below are read from the photo files, keyed by photo URL.
    /// 星级（人工、AI、机内或其他软件写入的 1–5 星）/ Stars (1–5, set by hand, by AI, in camera or by other apps).
    var userRatings: [URL: Int] = [:]
    var flags: [URL: PhotoFlag] = [:]
    /// 照片标题 `dc:title`，App 写入的是中文鸟名 / The photo title `dc:title`; the app writes the Chinese species name.
    var titles: [URL: String] = [:]
    /// 写照片文件（评分、旗标、鸟种信息）按顺序排队，同一个文件不会被同时写
    /// Writes into photo files (ratings, flags, species info) are queued so one file is never written twice at once.
    @ObservationIgnored var fileWrites: Task<Void, Never>?
    /// 已设置、还没写进文件的评分（0 为清除）和旗标；重新扫描时以它们为准
    /// Ratings (0 = clear) and flags set but not yet written; they win over what a rescan reads from the files.
    @ObservationIgnored var pendingRatings: [URL: Int] = [:]
    @ObservationIgnored var pendingFlags: [URL: PhotoFlag?] = [:]
    var analysis: AnalysisProgress?
    var alertMessage: String?
    var analysisTask: Task<Void, Never>?
    var thresholds = RatingThresholds.intermediate

    var title: String {
        switch sidebarSelection {
        case .all, nil: String(localized: "所有照片")
        case .recentImport: String(localized: "最近导入")
        case let .folder(url): url.lastPathComponent
        case let .stars(count): String(repeating: "★", count: count)
        case let .flag(flag): flag.title
        }
    }

    var visiblePhotos: [LibraryPhoto] {
        guard let snapshot else { return [] }
        switch sidebarSelection {
        case .all, nil: return snapshot.photos
        case .recentImport: return recentImport
        case let .folder(url): return snapshot.photos(in: url)
        case let .stars(count): return snapshot.photos.filter { userRatings[$0.url] == count }
        case let .flag(flag): return snapshot.photos.filter { self.flag(for: $0) == flag }
        }
    }

    /// 侧边栏各星级的数量 / Per-star counts for the sidebar.
    var starCounts: [Int: Int] {
        var counts: [Int: Int] = [:]
        for photo in snapshot?.photos ?? [] {
            if let stars = userRatings[photo.url] { counts[stars, default: 0] += 1 }
        }
        return counts
    }

    /// 分析的对象：有选择时只分析所选，否则分析当前显示的全部；结果写不进去的（视频、RAF）不分析
    /// What gets analysed: the selection if there is one, otherwise everything shown; files the results cannot be
    /// written into (videos, RAF) are skipped.
    var analysisTargets: [LibraryPhoto] {
        (selection.isEmpty ? visiblePhotos : visiblePhotos.filter { selection.contains($0.url) })
            .filter { RatingFile.canWrite($0.url) }
    }

    var isAnalyzing: Bool { analysis != nil }

    // MARK: 工具 / Helpers

    /// 提示里列出的文件名：最多 5 个，多出的用「等」表示 / File names listed in an alert: at most 5, "etc." for the rest.
    static func nameList(_ names: [String]) -> String {
        let list = names.prefix(5).joined(separator: String(localized: "、", comment: "文件名之间的分隔符 / separator between file names"))
        return names.count > 5 ? String(localized: "\(list) 等") : list
    }
}
