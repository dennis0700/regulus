import Foundation

/// 一个鸟种的名录信息：中文名（《中国鸟类名录》2026 版）、分类、IUCN 等级、GBIF 罕见度
/// Checklist info for one species: Chinese name (China checklist 2026), taxonomy, IUCN category, GBIF rarity.
public struct SpeciesInfo: Codable, Sendable, Equatable {
    public let zh: String
    public let en: String
    public let sci: String
    /// 是否收录于《中国鸟类名录》2026 版 / Whether it is in the China checklist 2026.
    public let inChina: Bool
    public let order: String
    public let family: String
    public let genus: String
    /// IUCN 红色名录等级代码（LC、NT、VU、EN、CR 等）/ IUCN Red List category code (LC, NT, VU, EN, CR, ...).
    public let iucn: String?
    /// GBIF 全球罕见度 0–100，越高越少见 / GBIF global rarity 0–100; higher is rarer.
    public let rarity: Double?

    /// IUCN 等级的中文名，未知代码原样返回 / Chinese name of the IUCN category; unknown codes are returned as-is.
    public var iucnTitle: String? {
        iucn.map { Self.iucnTitles[$0] ?? $0 }
    }

    /// 罕见度档位（同 SuperPicky）：<8 常见、<25 能见、<50 少见、<75 罕见，其余传奇
    /// Rarity tier (as SuperPicky): <8 常见, <25 能见, <50 少见, <75 罕见, otherwise 传奇.
    public var rarityTier: String? {
        guard let rarity else { return nil }
        let index = Self.rarityCuts.firstIndex { rarity < $0 } ?? Self.rarityCuts.count
        return Self.rarityTiers[index]
    }

    static let iucnTitles = ["LC": "无危", "NT": "近危", "VU": "易危", "EN": "濒危", "CR": "极危",
                             "EW": "野外灭绝", "EX": "灭绝", "DD": "数据缺乏", "NE": "未评估"]
    static let rarityCuts = [8.0, 25.0, 50.0, 75.0]
    static let rarityTiers = ["常见", "能见", "少见", "罕见", "传奇"]

    public init(zh: String, en: String, sci: String, inChina: Bool, order: String, family: String, genus: String,
                iucn: String?, rarity: Double?) {
        self.zh = zh
        self.en = en
        self.sci = sci
        self.inChina = inChina
        self.order = order
        self.family = family
        self.genus = genus
        self.iucn = iucn
        self.rarity = rarity
    }
}

/// 名录信息表（下标即鸟种库类别号），由 scripts/build_species_info.py 生成
/// The checklist table (index = species-DB id), generated by scripts/build_species_info.py.
///
/// # Examples
/// ```
/// let table = try SpeciesInfoTable(url: modelsDir.appendingPathComponent("birdtrace/species_info.json"))
/// table[833]?.zh          // "池鹭"
/// table[833]?.iucnTitle   // "无危"
/// ```
public struct SpeciesInfoTable: Sendable {
    let entries: [SpeciesInfo]
    /// 中文名 → 下标（重名取第一个）/ Chinese name -> index (the first one on duplicates).
    private let indexByName: [String: Int]

    public init(url: URL) throws {
        self.init(entries: try JSONDecoder().decode([SpeciesInfo].self, from: Data(contentsOf: url)))
    }

    public init(entries: [SpeciesInfo]) {
        self.entries = entries
        indexByName = Dictionary(entries.indices.map { (entries[$0].zh, $0) }, uniquingKeysWith: { first, _ in first })
    }

    /// 越界返回 nil / nil when out of range.
    public subscript(id: Int) -> SpeciesInfo? {
        entries.indices.contains(id) ? entries[id] : nil
    }

    /// 按中文名查（照片标题里写的是中文鸟名）；没有返回 nil / Look up by Chinese name (photo titles hold it); nil if
    /// unknown.
    ///
    /// # Examples
    /// ```
    /// table.info(named: "池鹭")?.en   // "Chinese Pond Heron"
    /// ```
    public func info(named zh: String) -> SpeciesInfo? {
        indexByName[zh].map { entries[$0] }
    }
}
